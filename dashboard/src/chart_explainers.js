// Formats explainer content by replacing placeholders with runtime values
export function formatExplainer(explainerId, runtimeContext = {}) {
  const base = CHART_EXPLAINERS[explainerId];
  if (!base) return null;

  const sf = runtimeContext.sf || 8;
  const sensVal = typeof runtimeContext.sensitivity === 'number'
    ? runtimeContext.sensitivity
    : (sf === 7 ? -123.0 : (sf === 8 ? -126.0 : (sf === 9 ? -128.5 : (sf === 10 ? -131.0 : (sf === 11 ? -134.0 : -137.0)))));
  const sensitivity = typeof runtimeContext.sensitivityStr === 'string'
    ? runtimeContext.sensitivityStr
    : `${sensVal.toFixed(1)} dBm`;

  const pathExpVal = typeof runtimeContext.pathExp === 'number' ? runtimeContext.pathExp : 3.8;
  const pathExp = pathExpVal.toFixed(1);

  const capacity = runtimeContext.capacity || '1000 mAh';
  const profile = runtimeContext.profile || 'field';
  const engine = runtimeContext.engine || 'C++ Native / WebAssembly RF Engine';
  const marginBudget = (14.0 - sensVal).toFixed(0);

  const snrLimitMap = { 7: -7.5, 8: -10.0, 9: -12.5, 10: -15.0, 11: -17.5, 12: -20.0 };
  const snrLimit = (snrLimitMap[sf] !== undefined ? snrLimitMap[sf] : -10.0).toFixed(1);

  const replacePlaceholders = (text) => {
    if (!text || typeof text !== 'string') return text;
    return text
      .replace(/{sf}/g, String(sf))
      .replace(/{sensitivity}/g, sensitivity)
      .replace(/{pathExp}/g, pathExp)
      .replace(/{capacity}/g, capacity)
      .replace(/{profile}/g, profile)
      .replace(/{engine}/g, engine)
      .replace(/{marginBudget}/g, marginBudget)
      .replace(/{snrLimit}/g, snrLimit);
  };

  const formattedAxis = {};
  if (base.axisExplanations) {
    for (const [k, v] of Object.entries(base.axisExplanations)) {
      formattedAxis[k] = replacePlaceholders(v);
    }
  }

  const formattedSeries = {};
  if (base.seriesExplanations) {
    for (const [k, v] of Object.entries(base.seriesExplanations)) {
      formattedSeries[k] = replacePlaceholders(v);
    }
  }

  return {
    ...base,
    title: replacePlaceholders(base.title),
    what: replacePlaceholders(base.what),
    why: replacePlaceholders(base.why),
    xy: replacePlaceholders(base.xy),
    howToRead: replacePlaceholders(base.howToRead),
    dataSources: replacePlaceholders(base.dataSources),
    caveats: replacePlaceholders(base.caveats),
    expertDetails: replacePlaceholders(base.expertDetails),
    axisExplanations: formattedAxis,
    seriesExplanations: formattedSeries
  };
}

