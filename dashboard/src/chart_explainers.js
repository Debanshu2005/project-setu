// Maps canvas ID or chart title to stable explainer ID
export function resolveExplainerId(canvasId, title = '') {
  if (canvasId) {
    const cleanId = canvasId.replace(/^canvas/, '');
    const map = {
      'RssiDistance': 'rssi_vs_distance_model',
      'PathLossDistance': 'path_loss_vs_theory',
      'SnrDistance': 'snr_vs_distance',
      'Heatmap': 'link_quality_matrix',
      'PdrTimeline': 'pdr_timeline',
      'LatencyCdf': 'latency_cdf',
      'Throughput': 'throughput_and_rate',
      'LossVsDistance': 'packet_loss_vs_distance',
      'HopDistribution': 'delivered_by_hop_count',
      'RelayActivity': 'relay_activity',
      'CollisionTimeline': 'collisions_vs_retransmission',
      'DropsTimeline': 'channel_loss_dynamics',
      'BatteryTimeline': 'fleet_soc',
      'EnergyLoad': 'energy_vs_forwarding',
      'Trajectory': 'trajectory_error_vectors',
      'PosErrorTimeline': 'position_error_timeline',
      'AckLatencyCdf': 'ack_latency_cdf',
      'AckCdf': 'ack_latency_cdf',
      'Ack': 'ack_latency_cdf',
      'CompCdf': 'comparative_latency_cdfs',
      'Comp': 'comparative_latency_cdfs',
      'SidebarQuick': title.includes('Latency') ? 'sidebar_latency_cdf' : 'sidebar_rssi_vs_distance'
    };
    if (map[cleanId]) return map[cleanId];
  }

  const t = (title || '').toLowerCase();
  if (t.includes('rssi vs') && t.includes('model')) return 'rssi_vs_distance_model';
  if (t.includes('path loss vs')) return 'path_loss_vs_theory';
  if (t.includes('snr') || t.includes('signal-to-noise')) return 'snr_vs_distance';
  if (t.includes('link quality matrix') || t.includes('link-quality')) return 'link_quality_matrix';
  if (t.includes('delivery ratio') || t.includes('pdr')) return 'pdr_timeline';
  if (t.includes('ack') && t.includes('cdf')) return 'ack_latency_cdf';
  if (t.includes('comparative') && t.includes('cdf')) return 'comparative_latency_cdfs';
  if (t.includes('latency cdf') || t.includes('latency')) return 'latency_cdf';
  if (t.includes('throughput') || t.includes('payload')) return 'throughput_and_rate';
  if (t.includes('packet loss probability') || t.includes('loss rate')) return 'packet_loss_vs_distance';
  if (t.includes('hop count')) return 'delivered_by_hop_count';
  if (t.includes('relay forward') || t.includes('relay activity')) return 'relay_activity';
  if (t.includes('collision')) return 'collisions_vs_retransmission';
  if (t.includes('channel loss dynamics') || t.includes('drops per')) return 'channel_loss_dynamics';
  if (t.includes('state of charge') || t.includes('battery')) return 'fleet_soc';
  if (t.includes('energy drain') || t.includes('energy vs')) return 'energy_vs_forwarding';
  if (t.includes('trajectory')) return 'trajectory_error_vectors';
  if (t.includes('position error')) return 'position_error_timeline';
  if (t.includes('rssi vs distance')) return 'sidebar_rssi_vs_distance';

  return null;
}

